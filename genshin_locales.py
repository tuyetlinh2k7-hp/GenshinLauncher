def get_text(key: str, lang: str = "vi", **kwargs) -> str:
    """Returns localized string with optional format arguments."""
    locale_dict = LOCALES.get(lang, LOCALES["vi"])
    text = locale_dict.get(key, LOCALES["vi"].get(key, key))
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text
